#!/usr/bin/env python3
"""Generate secrets.h for hub_connectivity_test.ino from your local secret files.

Source (git-ignored):
    secrets/hub-wifi.txt   WIFI_SSID, WIFI_PASS, SUPABASE_URL, SUPABASE_KEY
    (frontend/.env is only a fallback for the two Supabase values)
Output:
    tools/hub_connectivity_test/secrets.h   (git-ignored via **/secrets.h)

    python tools/hub_connectivity_test/make_secrets_h.py
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def kv(path: pathlib.Path) -> dict:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.rstrip("\r\n")
        if line.strip() and not line.lstrip().startswith("#") and "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip().strip('"').strip("'") if k.strip().startswith("VITE_") else v
    return out


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    sec = kv(ROOT / "secrets" / "hub-wifi.txt")
    env_path = ROOT / "frontend" / ".env"
    env = kv(env_path) if env_path.exists() else {}
    # secrets/hub-wifi.txt is the single source; frontend/.env is only a fallback
    vals = {
        "WIFI_SSID": sec.get("WIFI_SSID"),
        "WIFI_PASS": sec.get("WIFI_PASS"),
        "SUPABASE_URL": sec.get("SUPABASE_URL") or env.get("VITE_SUPABASE_URL"),
        "SUPABASE_KEY": sec.get("SUPABASE_KEY") or env.get("VITE_SUPABASE_ANON_KEY"),
    }
    missing = [n for n, v in vals.items() if not v]
    if missing:
        print("Missing values:", ", ".join(missing))
        return 2
    out = HERE / "secrets.h"
    out.write_text(
        "// AUTO-GENERATED by make_secrets_h.py - contains real credentials, NEVER commit.\n"
        f"#define WIFI_SSID     {c_str(vals['WIFI_SSID'])}\n"
        f"#define WIFI_PASS     {c_str(vals['WIFI_PASS'])}\n"
        f"#define SUPABASE_URL  {c_str(vals['SUPABASE_URL'].rstrip('/'))}\n"
        f"#define SUPABASE_KEY  {c_str(vals['SUPABASE_KEY'])}\n",
        encoding="utf-8")
    print(f"Wrote {out} (4 values). It is git-ignored; do not copy it elsewhere.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
